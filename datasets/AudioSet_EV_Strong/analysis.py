def load_mid_mapping(tsv_path):
    """Load MID to display name mapping."""
    mid_map = {}
    if not tsv_path.exists():
        return mid_map
    
    with open(tsv_path, 'r') as f:
        for line in f:
            parts = line.strip().split('\t')
            if len(parts) == 2:
                mid, display_name = parts
                mid_map[mid] = display_name
    return mid_map


def parse_metadata(metadata_paths, ev_mids):
    """
    Parse metadata TSV files and extract event statistics.
    
    Returns:
        dict with segment-level and event-level information
    """
    segment_info = defaultdict(lambda: {'events': [], 'has_ev': False, 'ev_mids': set()})
    
    for metadata_path in metadata_paths:
        if not Path(metadata_path).exists():
            print(f"  Warning: {metadata_path} not found")
            continue
        
        with open(metadata_path, 'r') as f:
            next(f)  # Skip header
            
            for line in f:
                parts = line.strip().split('\t')
                if len(parts) != 4:
                    continue
                
                segment_id, start_time, end_time, mid = parts
                
                try:
                    start_time = float(start_time)
                    end_time = float(end_time)
                except ValueError:
                    continue
                
                duration = end_time - start_time
                
                # Store event
                segment_info[segment_id]['events'].append({
                    'mid': mid,
                    'start': start_time,
                    'end': end_time,
                    'duration': duration
                })
                
                # Check if EV event
                if mid in ev_mids:
                    segment_info[segment_id]['has_ev'] = True
                    segment_info[segment_id]['ev_mids'].add(mid)
    
    return dict(segment_info)


def compute_event_statistics(segment_info, ev_mids):
    """Compute statistics about EV events."""
    stats = {
        'total_segments': len(segment_info),
        'segments_with_ev': 0,
        'segments_without_ev': 0,
        'total_ev_events': 0,
        'ev_durations': [],
        'ev_coverage': [],  # Percentage of 10s covered by EV
        'ev_types': Counter(),
        'num_windows_with_ev': [],  # Number of windows containing EV per segment
    }
    
    num_windows = int(np.ceil(TARGET_DURATION / WINDOW_SIZE))
    
    for segment_id, info in segment_info.items():
        if info['has_ev']:
            stats['segments_with_ev'] += 1
            
            # Create label track
            label_track = np.zeros(num_windows)
            window_samples = WINDOW_SIZE
            
            for event in info['events']:
                if event['mid'] in ev_mids:
                    stats['total_ev_events'] += 1
                    stats['ev_durations'].append(event['duration'])
                    stats['ev_types'][event['mid']] += 1
                    
                    # Mark windows
                    for i in range(num_windows):
                        window_start = i * window_samples
                        window_end = (i + 1) * window_samples
                        
                        # Check overlap
                        if window_start < event['end'] and event['start'] < window_end:
                            label_track[i] = 1
            
            # Compute coverage
            coverage = (label_track.sum() * WINDOW_SIZE) / TARGET_DURATION * 100
            stats['ev_coverage'].append(coverage)
            stats['num_windows_with_ev'].append(int(label_track.sum()))
        else:
            stats['segments_without_ev'] += 1
    
    return stats


