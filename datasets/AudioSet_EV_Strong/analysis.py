def plot_label_distribution_from_logs(logs, segment_info):
    """Plot label distribution: metadata vs found files."""
    if logs['v1'] is None or logs['v2'] is None:
        print("  Skipping label distribution plot (logs not available)")
        return
    
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(18, 7))
    
    # Count metadata labels (from segment_info)
    metadata_label_counts = Counter()
    for seg_data in segment_info.values():
        for mid in seg_data['ev_mids']:
            if mid in EV_MIDS:
                metadata_label_counts[EV_MIDS[mid]] += 1
    
    for ax, version in zip([ax1, ax2], ['v1', 'v2']):
        df = logs[version]
        df_found = df[df['found'] == True]
        
        # Count found labels
        found_label_counts = Counter()
        for labels_str in df_found['label']:
            if pd.notna(labels_str) and labels_str != 'N/A':
                # Split multiple labels (separated by '; ')
                labels = [l.strip() for l in str(labels_str).split(';')]
                for label in labels:
                    if label and label != 'Unknown':
                        found_label_counts[label] += 1
        
        # Prepare data for plotting (only EV labels)
        ev_labels = [EV_MIDS[mid] for mid in sorted(EV_MIDS.keys(), key=lambda x: metadata_label_counts[EV_MIDS[x]], reverse=True)]
        
        metadata_counts = [metadata_label_counts[label] for label in ev_labels]
        found_counts = [found_label_counts.get(label, 0) for label in ev_labels]
        
        # Plot double bars
        y_pos = np.arange(len(ev_labels))
        width = 0.35
        
        bars1 = ax.barh(y_pos - width/2, metadata_counts, width, 
                       label='In Metadata', color='#3498db', alpha=0.8, edgecolor='black', linewidth=1.2)
        bars2 = ax.barh(y_pos + width/2, found_counts, width, 
                       label='Found in Dataset', color='#27ae60', alpha=0.8, edgecolor='black', linewidth=1.2)
        
        ax.set_yticks(y_pos)
        ax.set_yticklabels(ev_labels, fontsize=11)
        ax.set_xlabel('Number of Segments', fontsize=12, fontweight='bold')
        ax.set_title(f'AudioSet_EV_{version}_Strong\\nLabel Distribution: Metadata vs Found', 
                    fontsize=13, fontweight='bold', pad=15)
        ax.legend(fontsize=10)
        ax.grid(axis='x', alpha=0.3, linestyle='--')
        ax.invert_yaxis()
        
        # Add value labels
        for i, (meta, found) in enumerate(zip(metadata_counts, found_counts)):
            ax.text(meta, i - width/2, f' {meta}', va='center', fontsize=9, fontweight='bold')
            ax.text(found, i + width/2, f' {found}', va='center', fontsize=9, fontweight='bold')
    
    plt.tight_layout()
    output_path = OUTPUT_DIR / "label_distribution_from_logs.svg"
    plt.savefig(output_path, format='svg', dpi=300, bbox_inches='tight')
